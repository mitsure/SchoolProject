"""Step7探索解析とStep8多変量解析を、既存Step6を壊さず追補資料へ反映する。"""
from __future__ import annotations

from pathlib import Path
import pandas as pd

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parent.parent
STEP8 = PROJECT / "CreateData" / "Step8_多変量解析"
OUTPUT = PROJECT / "CreateData" / "Step6_論文作成支援" / "Text"


def main() -> None:
    coefficients = pd.read_csv(STEP8 / "Step8-03_調整オッズ比.csv", encoding="utf-8-sig")
    diagnostics = pd.read_csv(STEP8 / "Step8-04_モデル診断.csv", encoding="utf-8-sig")
    if not diagnostics["収束"].all():
        raise RuntimeError("未収束モデルがあるため、論文反映案を生成しません。")

    targets = {
        ("高校", "高校"): "高校",
        ("通学中", "通学中"): "通学中",
        ("自転車", "自転車"): "自転車",
        ("道路", "道路"): "道路",
        ("通学状況の組合せ", "通学・自転車・道路"): "通学中かつ自転車かつ道路",
        ("通学状況の組合せ", "その他の通学中"): "その他の通学中",
    }
    selected = []
    for (model, item), label in targets.items():
        row = coefficients.loc[coefficients["モデル"].eq(model) & coefficients["項目"].eq(item)].iloc[0]
        selected.append({"項目": label, "調整オッズ比": row["調整オッズ比"],
                         "95%CI下限": row["95%CI下限"], "95%CI上限": row["95%CI上限"], "モデル": model})
    evidence = pd.DataFrame(selected)
    evidence.to_csv(OUTPUT / "Step6-7_Step7_8追加解析_数値根拠.csv", index=False, encoding="utf-8-sig")

    values = {row["項目"]: row for _, row in evidence.iterrows()}
    def result_text(name: str) -> str:
        row = values[name]
        return (f'{name}（調整オッズ比{row["調整オッズ比"]:.2f}、'
                f'95%信頼区間{row["95%CI下限"]:.2f}–{row["95%CI上限"]:.2f}）')

    document = f"""# Step6-7 Step7・8追加解析反映案

## この資料の扱い

本資料は既存のStep6下書きを上書きせず、Step7探索的解析およびStep8多変量解析を論文へ追記するための案である。数値はStep8出力から自動取得した。解析対象はStep2で抽出された長期的な障害事例カテゴリの統合データであり、学校事故全体における発生率や一般集団のリスクを示すものではない。

## Methods 追記案

Step2で抽出・確認済みのカテゴリ別事例を統合し、歯牙障害1,583件と歯牙障害以外6,099件の計7,682件を解析した。歯牙障害の有無を目的変数とし、高校、通学中、自転車および道路との関連をロジスティック回帰により評価した。高校のモデルでは性別および年度を考慮し、通学中、自転車、道路の各モデルでは学校種としての高校、性別および年度を考慮した。

通学中、自転車および道路は同一事例内で強く重なっていたため、3項目を同一モデルで独立した効果として推定しなかった。代わりに各項目の個別モデルに加え、「通学中かつ自転車かつ道路」「その他の通学中」「通学中以外」の相互に重ならない区分を作成した組合せモデルを解析した。推定値は調整オッズ比と95%信頼区間で示した。欠損により当該カテゴリへの該当を確認できない場合は非該当としてフラグ化した。

## Results 追記案

高校、通学中、自転車および道路は、性別、年度および必要に応じて高校区分を考慮した後も、歯牙障害と正の関連を示した。各推定値は、{result_text("高校")}、{result_text("通学中")}、{result_text("自転車")}、{result_text("道路")}であった。

通学状況を相互に重ならない区分で評価したモデルでは、通学中以外を基準として、{result_text("通学中かつ自転車かつ道路")}であった。一方、{result_text("その他の通学中")}であり、95%信頼区間は1を含んだ。

## Discussion 追記案

本解析では、単に「通学中」であることよりも、「自転車を利用し道路上で発生した通学中の事例」という組合せで歯牙障害との関連が強かった。これは、自転車走行中の転倒や顔面への直接的衝撃が関係する可能性を示す仮説であり、通学時の自転車安全教育、走行環境、ヘルメットおよび口腔・顔面保護の検討につながり得る。

ただし、本データは長期的な障害事例カテゴリを統合したもので、全児童生徒や全学校事故を分母とした発生率ではない。競技・通学への参加人数や走行距離も把握できず、観察された関連を原因と解釈することはできない。また、通学中、自転車、道路、高校は相互に重なり、測定されていない活動内容や事故状況の影響が残る可能性がある。原文を用いた受傷機転の確認と、欠損の扱いを変えた解析が今後必要である。

## 改訂抄録案

### 目的

学校管理下の障害事例データを用い、歯牙障害に特徴的な語・事故パターンを抽出するとともに、学校種および通学関連状況との関連を検討した。

### 方法

Step2で抽出・確認済みの7,682件（歯牙障害1,583件、歯牙障害以外6,099件）を解析した。自由記載に対して形態素解析、頻出語、TF-IDF、共起および類似性解析を実施した。さらに、歯牙障害の有無を目的変数とするロジスティック回帰を用い、高校、通学中、自転車および道路との関連を性別、年度および必要に応じて高校区分を考慮して評価した。通学関連3項目の強い重なりを考慮し、「通学中かつ自転車かつ道路」の組合せも評価した。

### 結果

歯牙障害事例では「前歯」「歯」「顔面」「口」などの語が特徴的であった。調整後の比較では、{result_text("高校")}、{result_text("自転車")}、{result_text("通学中かつ自転車かつ道路")}であった。その他の通学中は{values["その他の通学中"]["調整オッズ比"]:.2f}（95%信頼区間{values["その他の通学中"]["95%CI下限"]:.2f}–{values["その他の通学中"]["95%CI上限"]:.2f}）で、明確な関連を確認できなかった。

### 結論

歯牙障害には口腔・顔面に関する特徴語に加え、高校および自転車で道路上を通学する状況との関連が認められた。通学時の自転車事故は予防研究の優先候補となるが、本結果は選択された障害事例内の関連であり、因果関係や一般集団での発生リスクを示すものではない。

## 反映前に研究者が確認する点

1. 倫理審査、対象期間、選択・除外基準を正式情報で補う。
2. 欠損を非該当とした主解析に対し、欠損除外による感度分析を追加する。
3. 「高校・自転車・通学中・道路」を独立した原因として記述しない。
4. 抄録の文字数を投稿先規定に合わせて調整する。
5. 予防策に関する記述へ適切な先行研究を引用する。
"""
    (OUTPUT / "Step6-7_Step7_8追加解析反映案.md").write_text(document, encoding="utf-8")
    (OUTPUT / "Step6-7_Step7_8追加解析反映案.txt").write_text(document.removeprefix("# Step6-7 Step7・8追加解析反映案\n\n"), encoding="utf-8")
    print(f"Step6-7生成完了: {OUTPUT}")


if __name__ == "__main__":
    main()
